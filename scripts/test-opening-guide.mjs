import assert from 'node:assert/strict'
import { chromium } from 'playwright'

const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH })
try {
  const context = await browser.newContext({ viewport: { width: 320, height: 480 }, hasTouch: true, isMobile: true })
  const page = await context.newPage()
  const cdp = await context.newCDPSession(page)
  await cdp.send('Emulation.setSafeAreaInsetsOverride', { insets: { top: 16, left: 8, right: 8, bottom: 12 } })
  const button = name => page.getByRole('button', { name, exact: true })
  const cue = page.locator('.opening-guide')
  const board = page.locator('.battlefield')
  const silver = page.locator('.resources strong')
  const marked = page.locator('[data-suggested="true"]')
  await page.goto(process.argv[2] ?? 'http://localhost:4173/')
  await page.getByText('Ready offline', { exact: true }).waitFor()
  await context.setOffline(true)
  await page.reload()
  const enter = async () => {
    await button('Campaign').tap()
    await button('Enter battle').tap()
  }
  await enter()
  const original = await board.boundingBox()
  const checkFrame = async () => {
    assert.deepEqual(await board.boundingBox(), original)
    assert.deepEqual(await page.evaluate(() => [document.documentElement.scrollWidth, document.documentElement.scrollHeight]), [320, 480])
    const skip = await button('Skip tips').boundingBox()
    assert(skip.width >= 44 && skip.height >= 44 && skip.x >= 8 && skip.x + skip.width <= 312 && skip.y + skip.height <= 468)
    const row = await page.locator('.command-status').boundingBox()
    const label = await cue.boundingBox()
    assert(label.y >= row.y && label.y + label.height <= row.y + row.height)
  }
  assert.match(await cue.innerText(), /select the marked site/)
  await button('Empty tile, row 1, column 9').tap()
  assert.equal(await marked.count(), 1)
  assert.match(await cue.innerText(), /select the marked site/)
  assert.equal(await silver.innerText(), '90 silver')
  await marked.tap()
  assert.match(await cue.innerText(), /Tap Build Archer · 30 silver/)
  assert.equal(await silver.innerText(), '90 silver')
  await checkFrame()
  await page.getByRole('button', { name: /^Build Archer/ }).tap()
  assert.equal(await silver.innerText(), '60 silver')
  assert.equal(await page.getByRole('button', { name: /^Archer, row/ }).count(), 1)
  assert.match(await cue.innerText(), /Tap Start/)
  await checkFrame()
  await button('Start wave').tap()
  await button('Pause').waitFor()
  assert.equal(await cue.count(), 0)
  await page.reload()
  await enter()
  await button('Skip tips').tap()
  assert.equal(await cue.count(), 0)
  assert.equal(await marked.count(), 0)
  assert.equal(await silver.innerText(), '90 silver')
  assert.deepEqual(await board.boundingBox(), original)
  await button('Empty tile, row 2, column 3').tap()
  await page.getByRole('button', { name: /^Build Archer/ }).tap()
  assert.equal(await silver.innerText(), '60 silver')
  assert.equal(await cue.count(), 0)
  console.log('Offline 320 × 480: marked-site selection, one Archer purchase, Start, dismissal, safe touch targets and stable board passed.')
} finally {
  await browser.close()
}
