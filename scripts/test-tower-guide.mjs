import assert from 'node:assert/strict'
import { chromium } from 'playwright'

const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH })
try {
  const context = await browser.newContext({ viewport: { width: 320, height: 480 }, isMobile: true, hasTouch: true })
  const page = await context.newPage()
  const cdp = await context.newCDPSession(page)
  await cdp.send('Emulation.setSafeAreaInsetsOverride', { insets: { top: 16, right: 8, bottom: 12, left: 8 } })
  const button = name => page.getByRole('button', { name, exact: true })
  const silver = async () => Number((await page.locator('.resources strong').innerText()).match(/^(\d+) silver$/)[1])
  const stores = () => page.evaluate(() => Object.fromEntries(Object.entries(localStorage).sort()))
  const readTower = () => page.locator('.cells button[aria-pressed=true]').getAttribute('aria-label')
  await page.goto(process.argv[2] ?? 'http://localhost:4173/')
  await page.getByText('Ready offline', { exact: true }).waitFor()
  await context.setOffline(true)
  await page.reload()
  await page.clock.install({ time: new Date('2030-01-01T00:00:00Z') })
  await page.clock.pauseAt(new Date('2030-01-01T00:00:01Z'))
  await button('Campaign').tap()
  await button('Enter battle').tap()
  await button('Select marked site').tap()
  await page.getByRole('button', { name: /^Build Archer/ }).tap()
  const selected = await readTower()
  const battleBoard = await page.locator('.battlefield').boundingBox()
  await button('Start wave').tap()
  await page.clock.runFor(400)
  await button('Pause').tap()
  await page.clock.runFor(1100) // Let the battle checkpoint settle before comparing trial writes.
  await button('Battle orders').tap()
  await button('Towers').tap()
  for (const group of ['Damage', 'Slowing', 'Support']) await page.getByRole('heading', { name: group, exact: true }).waitFor()
  const originalStorage = await stores()
  assert.equal(originalStorage['3guotd.cleared-missions.v1'], undefined)
  for (const [tower, kind, card] of [
    ['Watch Beacon', 'beacon', 'Beacon'], ['Archer', 'volley', 'Archer'], ['Drum', 'drum', 'Drum'],
    ['Volley Platform', 'volley', 'Volley'], ['Heavy Crossbow', 'crossbow', 'Crossbow'],
  ]) {
    const entry = page.locator('.tower-guide-entry').filter({ has: page.getByRole('heading', { name: new RegExp(`^${tower} ·`) }) })
    const displayed = Number((await entry.getByRole('heading').innerText()).match(/(\d+) silver$/)[1])
    const tryTower = entry.getByRole('button', { name: `Try ${tower}`, exact: true })
    await tryTower.scrollIntoViewIfNeeded()
    const target = await tryTower.boundingBox()
    assert(target.width >= 44 && target.height >= 44)
    await tryTower.tap()
    assert.equal(await page.getByLabel('Trial tower').inputValue(), kind)
    const back = button('Back to Towers')
    const targetBack = await back.boundingBox()
    assert(targetBack.width >= 44 && targetBack.height >= 44 && targetBack.y >= 16)
    await button('Empty tile, row 2, column 6').tap()
    const purchase = page.getByRole('button', { name: new RegExp(`^Build ${card}`) })
    assert.equal(Number((await purchase.innerText()).match(/(\d+) silver/)[1]), displayed)
    const before = await silver()
    await purchase.tap()
    assert.equal(before - await silver(), displayed)
    assert.deepEqual(await page.evaluate(() => [document.documentElement.scrollWidth, document.documentElement.scrollHeight]), [320, 480])
    if (kind === 'beacon') {
      await page.goBack()
      await page.getByRole('heading', { name: 'Towers', exact: true }).waitFor()
      await page.goForward()
      assert.equal(await page.getByLabel('Trial tower').inputValue(), 'beacon')
    }
    await back.tap()
    await page.getByRole('heading', { name: 'Towers', exact: true }).waitFor()
  }
  await button('Back to orders').tap()
  await button('Back to battle').tap()
  await button('Resume').waitFor()
  assert.equal(await silver(), 60)
  assert.equal(await readTower(), selected)
  assert.deepEqual(await page.locator('.battlefield').boundingBox(), battleBoard)
  assert.deepEqual(await stores(), originalStorage)

  await button('Resume').tap()
  await button('Battle orders').tap()
  await button('Towers').tap()
  await button('Try Watch Beacon').tap()
  await button('Start wave').tap()
  await page.clock.runFor(1200)
  await page.goBack()
  await page.goBack()
  await page.goBack()
  await button('Pause').waitFor()
  assert.equal(await silver(), 60)
  assert.equal(await readTower(), selected)
  console.log('Offline 320 × 480: five guide prices, all direct trials, Back and Forward, battle selection, silver, and both pause states passed.')
} finally {
  await browser.close()
}
